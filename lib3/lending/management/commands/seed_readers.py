class Command(BaseCommand):
    help = 'Массово добавляет читателей в БД филиала'

    def add_arguments(self, parser):
        parser.add_argument(
            '--branch', type=str, default='branch_1',
            help='Псевдоним БД филиала (branch_1 или branch_2). По умолч.: branch_1'
        )
        parser.add_argument(
            '--count', type=int, default=None,
            help='Сколько читателей добавить (по умолч. все из списка)'
        )

    def handle(self, *args, **options):
        db = options['branch']
        data = READERS_DATA[:options['count']] if options['count'] else READERS_DATA

        created = 0
        skipped = 0

        for i, (last_name, first_name, middle_name, phone) in enumerate(data, start=1):
            # Уникальный номер билета: BRANCH-ПОРЯДКОВЫЙ
            prefix = db.replace('branch_', 'B')
            card_number = f'{prefix}-{i:05d}'

            if Reader.objects.using(db).filter(card_number=card_number).exists():
                skipped += 1
                continue

            Reader.objects.using(db).create(
                first_name=first_name,
                last_name=last_name,
                middle_name=middle_name,
                card_number=card_number,
                phone=phone,
                is_active=True,
            )
            created += 1

        self.stdout.write(
            self.style.SUCCESS(
                f'✅ [{db}] Добавлено читателей: {created} | Уже существовало: {skipped}'
            )
        )
